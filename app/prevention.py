def _isolate_partner(analysis, student_id):
    """Кого предложить изоляту в пару.

    Берём того, кого он выбрал сам: одностороннюю симпатию проще превратить во
    взаимную, чем строить связь с нуля.
    """
    for edge in analysis["edges"]:
        if edge["from"] == student_id:
            return edge["to"]
    return None


def recommendations(analysis, names=None):
    """Что предложить психологу по итогам среза.

    analysis — результат build_analysis (или снапшот).
    names — {student_id: ФИО}, чтобы подставить имена в подсказки.

    Возвращает список предложений, отсортированный по срочности. На
    недостоверном срезе — пустой список и причина.
    """
    names = names or {}
    gm = analysis["graph_metrics"]

    # Класс, в котором почти некого связывать. Социометрия на таких размерах
    # бессмысленна: «низкая плотность» в классе из двух человек — арифметика,
    # а не проблема, и предлагать по ней тренинг на сплочение странно.
    if gm["students"] < MIN_CLASS_FOR_ADVICE:
        return {
            "available": False,
            "reason": (
                "В классе %d %s — для социометрии этого мало. Добавьте учеников "
                "и проведите срез." % (gm["students"], _plural(gm["students"]))
            ),
            "items": [],
        }

    if gm["reliability"] == "low":
        return {
            "available": False,
            "reason": (
                "Опрос прошли менее 70%% класса (%d из %d). По таким данным нельзя "
                "отличить изоляцию от того, что ребёнка просто некому было выбрать, — "
                "рекомендации не строятся."
                % (gm["responded"], gm["students"])
            ),
            "items": [],
        }

    # Ни одного положительного выбора — значит опрос прошли, но никто никого не
    # выбрал (или срез пустой). Метрики тут все нулевые по определению, и
    # выкатывать по ним пять рекомендаций сразу — шум, а не помощь.
    if not gm["positive_edges"]:
        return {
            "available": False,
            "reason": (
                "В срезе нет ни одного положительного выбора — строить рекомендации "
                "не по чему. Проверьте, что ученики действительно прошли опрос."
            ),
            "items": [],
        }

    per = analysis["per_student"]
    items = []

    # --- изоляты: самое срочное, работа адресная ---
    isolates = [int(k) for k, m in per.items() if m["status"] == "isolate"]
    if isolates:
        pairs = []
        for sid in isolates:
            partner = _isolate_partner(analysis, sid)
            pairs.append({
                "student_id": sid,
                "student_name": names.get(sid, "—"),
                "partner_id": partner,
                "partner_name": names.get(partner) if partner else None,
            })
        tmpl = PLAYBOOK["isolated"]
        items.append({
            "code": "isolated",
            "priority": 1,
            "reason": "Без входящих выборов: %d %s" % (len(isolates), _plural(len(isolates))),
            "student_ids": isolates,
            "pairs": pairs,
            **tmpl,
        })

    # --- устойчивые номинации «часто один» ---
    marked = [int(k) for k, m in per.items() if m["alone_reportable"]]
    if marked:
        tmpl = PLAYBOOK["alone_marked"]
        items.append({
            "code": "alone_marked",
            "priority": 2,
            "reason": "Класс отмечает как одиноких: %d %s (от %d номинаций)"
                      % (len(marked), _plural(len(marked)), ALONE_MIN_REPORT),
            # Мероприятие на весь класс: адресовать его конкретному ребёнку
            # значит указать на него пальцем.
            "student_ids": [],
            **tmpl,
        })

    # --- класс в целом ---
    if gm["density"] < LOW_DENSITY:
        items.append({
            "code": "low_density", "priority": 3, "student_ids": [],
            "reason": "Низкая плотность связей: %.2f" % gm["density"],
            **PLAYBOOK["low_density"],
        })

    if gm["reciprocity"] < LOW_RECIPROCITY:
        items.append({
            "code": "low_reciprocity", "priority": 4, "student_ids": [],
            "reason": "Мало взаимных выборов: взаимность %d%%" % round(gm["reciprocity"] * 100),
            **PLAYBOOK["low_reciprocity"],
        })

    if gm["communities"] >= MANY_COMMUNITIES and gm["students"] >= 8:
        items.append({
            "code": "fragmented", "priority": 5, "student_ids": [],
            "reason": "Класс распался на %d обособленные группы" % gm["communities"],
            **PLAYBOOK["fragmented"],
        })

    if gm["bridges"] and gm["bridges"] <= BRIDGE_FRAGILITY + 1:
        items.append({
            "code": "bridges", "priority": 6, "student_ids": [],
            "reason": "Класс держится на %d связ%s — их потеря разорвёт его на части"
                      % (gm["bridges"], "и" if gm["bridges"] == 1 else "ях"),
            **PLAYBOOK["bridges"],
        })

    # Родительское собрание предлагаем, когда есть о чём говорить.
    if isolates or marked:
        items.append({
            "code": "parents", "priority": 7, "student_ids": [],
            "reason": "В классе есть дети с трудностями в общении",
            **PLAYBOOK["parents"],
        })

    items.sort(key=lambda x: x["priority"])
    return {"available": True, "reason": None, "items": items}


def _plural(n):
    if n % 10 == 1 and n % 100 != 11:
        return "ученик"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "ученика"
    return "учеников"


def effect_report(before, after, student_ids):
    """Сравнение «до/после» по охваченным ученикам.

    before/after — результаты анализа двух срезов, student_ids — кто был
    охвачен мероприятием.

    Осознанное ограничение: это НАБЛЮДЕНИЕ, а не доказательство эффекта.
    Контрольной группы нет, между срезами в классе происходит многое помимо
    занятия, и приписывать изменение только ему было бы неверно. Поэтому
    рядом со сводкой по охваченным считается сводка по остальному классу —
    если связи выросли у всех одинаково, дело не в мероприятии.
    """
    if before is None or after is None:
        return {"available": False, "reason": "Нужны два закрытых среза: до мероприятия и после."}
    for a in (before, after):
        if a["graph_metrics"]["reliability"] == "low":
            return {"available": False,
                    "reason": "Один из срезов недостоверен (явка ниже 70%) — сравнивать нельзя."}

    covered = set(student_ids or [])
    rows, others = [], []
    for key, now in after["per_student"].items():
        sid = int(key)
        was = before["per_student"].get(key)
        if not was or was["status"] == "unknown" or now["status"] == "unknown":
            continue
        delta = {
            "student_id": sid,
            "in_before": was["in_degree"], "in_after": now["in_degree"],
            "in_delta": now["in_degree"] - was["in_degree"],
            "mutual_before": was["mutual"], "mutual_after": now["mutual"],
            "mutual_delta": now["mutual"] - was["mutual"],
            "was_isolate": was["status"] == "isolate",
            "is_isolate": now["status"] == "isolate",
        }
        (rows if sid in covered else others).append(delta)

    def summarize(group):
        if not group:
            return None
        return {
            "students": len(group),
            "avg_in_delta": round(sum(r["in_delta"] for r in group) / len(group), 2),
            "avg_mutual_delta": round(sum(r["mutual_delta"] for r in group) / len(group), 2),
            "left_isolation": sum(1 for r in group if r["was_isolate"] and not r["is_isolate"]),
            "became_isolate": sum(1 for r in group if not r["was_isolate"] and r["is_isolate"]),
        }

    return {
        "available": True,
        "reason": None,
        "covered": summarize(rows),
        "rest_of_class": summarize(others),
        "details": sorted(rows, key=lambda r: r["in_delta"]),
        "disclaimer": (
            "Это наблюдение, а не доказательство эффекта: контрольной группы нет, "
            "и между срезами в классе происходит многое помимо занятия. Сравните "
            "изменение у охваченных с остальным классом — если оно одинаковое, "
            "дело, скорее всего, не в мероприятии."
        ),
    }
